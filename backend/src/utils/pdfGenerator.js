/**
 * FinTrace NCRP — investigation PDF dossier generator.
 *
 * Assembles a professional, multi-page PDF from a report's analysis bundle
 * using PDFKit. The dossier leads with a visual section — charts are built as
 * SVG and rasterised to PNG (see ./charts.js) for reliable printing — then
 * relegates the bulky data tables to a clearly labelled Annexure at the back.
 *
 * Front matter (one section per page):
 *    Cover                   — case title, date, headline numbers, sign-off.
 *    1. Executive Summary    — key figures in a two-column table.
 *    2. Visual Summary       — money-flow network, layer-breakdown, and daily-
 *                              volume charts (rasterised PNGs).
 *    3. Investigation Roadmap— prioritised P0–P3 action table.
 *    4. Key Findings         — the analyzer's auto-generated action list.
 * Annexure (supporting data tables, behind a divider page):
 *    A. Layer Analysis       — per-layer aggregates.
 *    B. Money Flow Network   — heaviest account→account edges.
 *    C. Top Mule Accounts    — top 10 by score, with risk band.
 *    D. Lien Worksheet       — recoverable amounts per account.
 *    E. Cashout Analysis     — ATM hotspots, same-day cashouts, state spread.
 *    F. Geographic Hotspots  — cashout by state + top POS merchants.
 *    G. Timeline             — daily money movement.
 *    H. Data Quality         — bank-attribution review.
 * Followed by: Draft Emails  — every per-bank lien letter, copy-paste ready.
 * Every page carries the footer "Generated by FinTrace NCRP | MINT" + page x/N.
 *
 * Amounts use an ASCII "Rs." prefix rather than the ₹ glyph, which is absent
 * from PDFKit's built-in (WinAnsi) Helvetica and would otherwise render blank.
 *
 * @module backend/src/utils/pdfGenerator
 */

