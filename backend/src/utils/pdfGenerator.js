/**
 * Cover page — full-bleed banner, headline figures, and a sign-off block.
 *
 * @param {PDFKit.PDFDocument} doc
 * @param {{ ackNo: string, generatedStr: string, victimLoss: number,
 *   trailDisputed: number, totalTxns: number, totalLayers: number,
 *   fraudStart: string,
 *   provenance?: { sha256: string|null, filename: string|null,
 *     ingestedAt: string|null, version: string } }} c
 */
function renderCover(doc, c) {
  const left = doc.page.margins.left;

  // Banner.
  doc.save();
  doc.rect(0, 0, doc.page.width, 150).fill(NAVY);
  doc.fillColor('#ffffff').font('Helvetica-Bold').fontSize(28).text('FinTrace NCRP', left, 48);
  doc.font('Helvetica').fontSize(13)
    .text('Cyber Crime Financial Trail — Investigation Dossier', left, 92);
  doc.restore();

  doc.fillColor(INK).font('Helvetica-Bold').fontSize(20)
    .text('Investigation Report', left, 195);
  doc.moveDown(1.2);
  doc.x = left;

  drawTable(doc, {
    fontSize: 11,
    columns: [
      { label: 'Field', width: 200 },
      { label: 'Value', width: contentWidth(doc) - 200 },
    ],
    rows: [
      ['Case / Acknowledgement No.', c.ackNo],
      ['Report Generated', c.generatedStr],
      ['Fraud Trail Start Date', c.fraudStart],
      ['Victim Loss (Layer 1)', formatMoney(c.victimLoss)],
      ['Total Trail Disputed (all layers)', formatMoney(c.trailDisputed)],
      ['Total Transactions', formatCount(c.totalTxns)],
      ['Layers Detected', formatCount(c.totalLayers)],
    ],
  });

  // ── Source & Provenance ─────────────────────────────────────────────
  // Court-grade traceability: the dossier is bound to the exact source file by
  // its SHA-256 (also stamped in every page footer + the PDF metadata).
  const prov = c.provenance || {};
  doc.moveDown(1.2);
  doc.x = left;
  doc.fillColor(NAVY).font('Helvetica-Bold').fontSize(12)
    .text('Source & Provenance', left, doc.y);
  const ruleY = doc.y + 2;
  doc.moveTo(left, ruleY).lineTo(doc.page.width - doc.page.margins.right, ruleY)
    .lineWidth(1).strokeColor(NAVY).stroke();
  doc.moveDown(0.6);
  doc.x = left;

  const provRow = (label, value, mono) => {
    doc.font('Helvetica-Bold').fontSize(9.5).fillColor(INK)
      .text(`${label}  `, left, doc.y, { continued: true, width: contentWidth(doc) })
      .font(mono ? 'Courier' : 'Helvetica').fillColor(INK)
      .text(String(value), { width: contentWidth(doc) });
    doc.moveDown(0.35);
    doc.x = left;
  };
  provRow('Source file:', prov.filename || 'Not recorded');
  provRow('Source SHA-256:', prov.sha256 || 'Not recorded (legacy report)', true);
  provRow('Ingested (UTC):', formatDate(prov.ingestedAt));
  provRow('FinTrace version:', prov.version || appVersion());
  doc.font('Helvetica-Oblique').fontSize(8).fillColor(MUTED).text(
    'The SHA-256 above is computed over the raw uploaded NCRP file before parsing. ' +
    'It is repeated in the footer of every page and embedded in this PDF\'s metadata, ' +
    'so any extracted page remains traceable to its source.',
    left, doc.y, { width: contentWidth(doc) });
  doc.x = left;

  doc.moveDown(1.4);
  doc.x = left;
  doc.font('Helvetica-Bold').fontSize(11).fillColor(INK);
  const line = (label) => {
    doc.text(`${label}  `, left, doc.y, { continued: true })
      .font('Helvetica').fillColor(MUTED).text('______________________________________')
      .font('Helvetica-Bold').fillColor(INK);
    doc.moveDown(0.8);
  };
  doc.text('Prepared / reviewed by:', left, doc.y);
  doc.moveDown(0.8);
  line('Case Officer :');
  line('Designation  :');
  line('Signature    :');
  line('Date         :');

  doc.moveDown(1.5);
  doc.font('Helvetica-Oblique').fontSize(8.5).fillColor(MUTED).text(
    'CONFIDENTIAL — For official use only. This dossier is generated from an NCRP ' +
    'BankAction CompleteTrail export and is intended solely for authorised ' +
    'investigation and judicial proceedings.',
    left, doc.y, { width: contentWidth(doc) }
  );
}

/**
 * @param {PDFKit.PDFDocument} doc
 * @param {object} a - The analysis bundle.
 * @param {Array<object>} liens
 */
function renderExecutiveSummary(doc, a, liens) {
  sectionHeading(doc, '1. Executive Summary');
  para(doc,
    'Key figures for this case at a glance. The Visual Summary (section 2) charts ' +
    'these figures; the full underlying tables follow in the Annexure at the back.',
    { gap: 0.8 });

  const summary = a.summary || {};
  const cashout = a.cashout_analysis || {};
  const mules = a.mule_detection || [];
  const highMules = mules.filter((m) => m.risk_label === 'HIGH').length;
  // Two distinct figures — never conflate (see analyzer summary):
  //   • recoverableResidual: victim loss not yet cashed out / frozen / refunded.
  //   • lienTableTotal: Σ per-account lien-eligible balances (can exceed the loss).
  const recoverableResidual = num(summary.recoverable_residual);
  const lienTableTotal = num(summary.lien_table_total) || (liens || []).reduce(
    (s, l) => s + num(l.lien_amount ?? l.lien_eligible_amount), 0);
  const banks = new Set((liens || []).map((l) => l.bank_name).filter(Boolean)).size;
  const cashedOut = cashedOutForDisplay(summary, cashout);

  drawTable(doc, {
    fontSize: 10,
    columns: [
      { label: 'Metric', width: 300 },
      { label: 'Value', width: contentWidth(doc) - 300, align: 'right' },
    ],
    rows: [
      ['Total transactions analysed', formatCount(summary.total_transactions)],
      ['Victim loss (Layer 1)', formatMoney(summary.victim_loss_amount ?? summary.total_disputed_amount)],
      ['Total trail disputed (all layers)', formatMoney(summary.total_trail_disputed ?? summary.total_disputed_amount)],
      ['Layers in the money trail', formatCount(summary.total_layers)],
      ['Distinct beneficiary accounts', formatCount(summary.total_accounts)],
      ['Fraud trail start date', formatDate(summary.fraud_start_date)],
      ['Total confirmed cashed out (ATM/POS)', formatMoney(cashedOut)],
      ['Recoverable residual (loss - cashed out - on hold - refunded)', formatMoney(recoverableResidual)],
      ['Same-day ATM cashouts', formatCount(cashout.same_day_cashouts)],
      ['High-risk mule accounts', formatCount(highMules)],
      ['Accounts with lien-eligible balance', formatCount((liens || []).length)],
      ['Total lien-eligible balance across flagged accounts', formatMoney(lienTableTotal)],
      ['Banks to be contacted for lien', formatCount(banks)],
    ],
  });

  para(doc,
    'Recoverable residual is the share of the victim loss not yet cashed out, frozen, or refunded — ' +
    'it sums with those to 100% of the loss. The total lien-eligible balance is the per-account freezable ' +
    'sum and may exceed the victim loss because funds are re-counted as they traverse multiple layers.',
    { gap: 0.6, size: 8.5, color: MUTED });

  para(doc, 'Note: the Visual Summary (section 2) presents the money-flow network, ' +
    'layer breakdown, and daily-volume timeline as charts. Every supporting table ' +
    'is reproduced in full in the Annexure (A-H) at the back of this dossier.',
    { gap: 0, size: 8.5, color: MUTED });
}

/**
 * Place one rasterised chart (PNG buffer + authored px dimensions) at the
 * current cursor, scaled to the content width, with an italic caption beneath.
 * Adds a page first if the image + caption would overflow the current one.
 *
 * @param {PDFKit.PDFDocument} doc
 * @param {{ png: Buffer, w: number, h: number }|null} chart
 * @param {string} caption
 */
function placeChart(doc, chart, caption) {
  const left = doc.page.margins.left;
  const w = contentWidth(doc);
  if (!chart || !chart.png) {
    para(doc, `[${caption}] — chart unavailable; see the Annexure tables for the data.`,
      { color: MUTED, gap: 0.8 });
    return;
  }
  const dispH = w * (chart.h / chart.w);
  // Reserve room for the image plus its caption line (~26pt).
  if (doc.y + dispH + 26 > doc.page.height - doc.page.margins.bottom) doc.addPage();
  doc.image(chart.png, left, doc.y, { width: w });
  doc.y += dispH + 3; // doc.image does not advance the cursor
  doc.font('Helvetica-Oblique').fontSize(8.5).fillColor(MUTED)
    .text(caption, left, doc.y, { width: w, align: 'left' });
  doc.x = left;
  doc.moveDown(1);
}

/**
 * Visual Summary — the charts section that sits up front (after the executive
 * summary). Renders the money-flow network, layer breakdown, and daily-volume
 * timeline as embedded PNGs; the same figures appear as full tables in the
 * Annexure. Degrades gracefully to a pointer note if rasterisation is
 * unavailable in this build.
 *
 * @param {PDFKit.PDFDocument} doc
 * @param {{ available: boolean, network: object, layers: object, timeline: object }} charts
 */
function renderVisualSummary(doc, charts) {
  sectionHeading(doc, '2. Visual Summary');
  para(doc,
    'The fund trail at a glance. These charts are generated deterministically from ' +
    'the case data (same case -> same charts); the complete figures behind each are ' +
    'tabulated in the Annexure.', { gap: 0.8 });

  if (!charts || !charts.available) {
    para(doc,
      'Charts could not be rendered in this build of FinTrace. The complete ' +
      'underlying data is available as tables in the Annexure (A-H).', { color: MUTED });
    return;
  }

  placeChart(doc, charts.network,
    'Money-flow network: the heaviest account-to-account transfers, laid out by layer from the '
    + 'victim (left) to cash-out exit nodes (right). Edge width is proportional to the amount '
    + 'transferred; node colour marks the role (victim / mule / exit). Accounts are masked.');
  placeChart(doc, charts.layers,
    'Layer breakdown: total amount moved at each layer (hop) of the trail, showing how the '
    + 'funds fan out and thin as they move away from the victim.');
  placeChart(doc, charts.timeline,
    'Daily volume timeline: transaction volume per IST day across the trail. The green portion '
    + 'and markers flag days with same-day cash-outs, surfacing rapid-extraction clusters.');
}

