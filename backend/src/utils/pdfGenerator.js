'use strict';

/**
 * FinTrace NCRP — investigation PDF dossier generator.
 *
 * Assembles a professional, multi-page (10+) PDF from a report's analysis
 * bundle using PDFKit. No chart rasterization happens here (that would pull in
 * canvas/puppeteer) — instead every visual is rendered as a full data table,
 * and a one-line pointer tells the reader to open the dashboard for charts.
 *
 * Sections, each starting on its own page:
 *    1. Cover                — case title, date, headline numbers, sign-off.
 *    2. Executive Summary    — key figures in a two-column table.
 *    3. Investigation Roadmap— prioritised P0–P3 action table.
 *    4. Layer Analysis       — per-layer aggregates.
 *    5. Money Flow Network   — heaviest account→account edges.
 *    6. Top Mule Accounts    — top 10 by score, with risk band.
 *    7. Lien Worksheet       — recoverable amounts per account.
 *    8. Cashout Analysis     — ATM hotspots, same-day cashouts, state spread.
 *    9. Geographic Hotspots  — cashout by state + top POS merchants.
 *   10. Timeline             — daily money movement.
 *   11. Key Findings         — the analyzer's auto-generated action list.
 *   12. Draft Emails         — every per-bank lien letter, copy-paste ready.
 * Every page carries the footer "Generated by FinTrace NCRP | MINT" + page x/N.
 *
 * Amounts use an ASCII "Rs." prefix rather than the ₹ glyph, which is absent
 * from PDFKit's built-in (WinAnsi) Helvetica and would otherwise render blank.
 *
 * @module backend/src/utils/pdfGenerator
 */

const fs = require('fs');
const path = require('path');
const PDFDocument = require('pdfkit');

// ─── Palette + layout constants ──────────────────────────────────────

const NAVY = '#1f3a5f';
const NAVY_LIGHT = '#33567f';
const INK = '#222222';
const MUTED = '#6b7785';
const ZEBRA = '#eef2f7';
const BORDER = '#cfd8e3';
const RISK_COLOR = Object.freeze({ HIGH: '#b00020', MEDIUM: '#b26a00', LOW: '#2e7d32' });
// Roadmap priority → text colour + printable severity label (red/amber/blue/grey).
const PRIORITY_COLOR = Object.freeze({ P0: '#b00020', P1: '#b26a00', P2: '#1565c0', P3: '#6b7785' });
const PRIORITY_LABEL = Object.freeze({ P0: 'P0 Critical', P1: 'P1 High', P2: 'P2 Medium', P3: 'P3 Low' });

const PAGE_MARGIN = 50;
const BRAND_FOOTER = 'Generated by FinTrace NCRP | MINT';

// ─── Number / date formatting ────────────────────────────────────────

/** @param {unknown} v */
function num(v) {
  const n = typeof v === 'number' ? v : Number(v);
  return Number.isFinite(n) ? n : 0;
}

/**
 * The confirmed cash-out figure the dossier prints. Reads the single source of
 * truth (`summary.cashed_out`, the capped policy figure), falling back to the
 * cash-out view for analyses produced before that field existed.
 *
 * @param {Record<string, unknown>} summary
 * @param {Record<string, unknown>} cashout
 * @returns {number}
 */
function cashedOutForDisplay(summary = {}, cashout = {}) {
  return summary.cashed_out != null ? num(summary.cashed_out) : num(cashout.total_cashout_amount);
}

/**
 * Rupee amount with Indian digit grouping and an ASCII "Rs." prefix.
 * @param {unknown} value
 * @returns {string}
 */
function formatMoney(value) {
  const v = num(value);
  const neg = v < 0;
  const [intPart, decPart] = Math.abs(v).toFixed(2).split('.');
  let last3 = intPart.slice(-3);
  const rest = intPart.slice(0, -3);
  if (rest !== '') last3 = ',' + last3;
  const grouped = rest.replace(/\B(?=(\d{2})+(?!\d))/g, ',') + last3;
  return `${neg ? '-' : ''}Rs. ${grouped}.${decPart}`;
}

/** Integer with Indian grouping (counts). @param {unknown} value */
function formatCount(value) {
  return num(value).toLocaleString('en-IN');
}

/** "DD Mon YYYY" in UTC, or an em dash. @param {unknown} iso */
function formatDate(iso) {
  if (iso === null || iso === undefined || iso === '') return '—';
  const d = new Date(iso);
  if (Number.isNaN(d.getTime())) return String(iso);
  const months = ['Jan', 'Feb', 'Mar', 'Apr', 'May', 'Jun',
    'Jul', 'Aug', 'Sep', 'Oct', 'Nov', 'Dec'];
  return `${String(d.getUTCDate()).padStart(2, '0')} ${months[d.getUTCMonth()]} ${d.getUTCFullYear()}`;
}

/** Mask all but the last 4 chars of an account number. @param {unknown} acc */
function maskAccount(acc) {
  const s = String(acc ?? '').trim();
  if (s.length <= 4) return s || '—';
  return `${'X'.repeat(Math.min(6, s.length - 4))}${s.slice(-4)}`;
}

/**
 * Replace glyphs absent from PDFKit's built-in WinAnsi Helvetica (which render
 * as blank boxes) with ASCII equivalents. The analyzer embeds ₹, ≥, →, and
 * smart quotes in human-readable roadmap/finding text; this keeps them legible.
 *
 * @param {unknown} v
 * @returns {string}
 */
function asciiSafe(v) {
  return String(v ?? '')
    .replace(/₹\s?/g, 'Rs. ')          // ₹ (rupee sign)
    .replace(/≥/g, '>=')                // ≥
    .replace(/≤/g, '<=')                // ≤
    .replace(/→/g, '->')                // →
    .replace(/[‘’‚]/g, "'")   // ‘ ’ ‚  → '
    .replace(/[“”„]/g, '"')   // “ ” „  → "
    .replace(/…/g, '...')               // … (horizontal ellipsis)
    .replace(/[–—−]/g, '-');       // – (en) — (em) − (U+2212 minus) → ASCII hyphen-minus
}

// ─── Low-level drawing helpers ───────────────────────────────────────

/** Usable content width between margins. @param {PDFKit.PDFDocument} doc */
function contentWidth(doc) {
  return doc.page.width - doc.page.margins.left - doc.page.margins.right;
}

/**
 * Section heading with an accent underline. Resets the cursor to the left
 * margin and leaves a sensible gap before the body.
 *
 * @param {PDFKit.PDFDocument} doc
 * @param {string} title
 */
function sectionHeading(doc, title) {
  const left = doc.page.margins.left;
  doc.fillColor(NAVY).font('Helvetica-Bold').fontSize(15).text(title, left, doc.y);
  const y = doc.y + 3;
  doc.moveTo(left, y).lineTo(doc.page.width - doc.page.margins.right, y)
    .lineWidth(1.5).strokeColor(NAVY).stroke();
  doc.moveDown(0.9);
  doc.x = left;
  doc.fillColor(INK).font('Helvetica').fontSize(10);
}

/**
 * Body paragraph at full content width from the left margin.
 *
 * @param {PDFKit.PDFDocument} doc
 * @param {string} text
 * @param {{ gap?: number, size?: number, color?: string, bold?: boolean }} [opts]
 */
function para(doc, text, opts = {}) {
  const left = doc.page.margins.left;
  doc.font(opts.bold ? 'Helvetica-Bold' : 'Helvetica')
    .fontSize(opts.size ?? 10)
    .fillColor(opts.color ?? INK)
    .text(text, left, doc.y, { width: contentWidth(doc), align: 'left' });
  if (opts.gap !== 0) doc.moveDown(opts.gap ?? 0.5);
  doc.x = left;
}

/**
 * Render a bordered, zebra-striped table that paginates itself, redrawing the
 * header row at the top of each continuation page.
 *
 * @param {PDFKit.PDFDocument} doc
 * @param {{
 *   columns: Array<{ label: string, width: number, align?: 'left'|'right'|'center' }>,
 *   rows: Array<Array<string|number>>,
 *   fontSize?: number,
 *   rowColors?: Array<string|null>,
 * }} spec - `rowColors[i]`, when set, tints that row's text (overrides zebra text).
 */
function drawTable(doc, { columns, rows, fontSize = 9, rowColors = [] }) {
  const startX = doc.page.margins.left;
  const padH = 5;
  const padV = 5;
  const totalWidth = columns.reduce((s, c) => s + c.width, 0);

  const measure = (cells, bold) => {
    doc.font(bold ? 'Helvetica-Bold' : 'Helvetica').fontSize(fontSize);
    let max = 0;
    for (let i = 0; i < columns.length; i++) {
      const h = doc.heightOfString(String(cells[i] ?? ''), {
        width: columns[i].width - padH * 2,
        align: columns[i].align || 'left',
      });
      if (h > max) max = h;
    }
    return max + padV * 2;
  };

  const paint = (cells, top, height, { bold = false, fill = null, textColor = INK } = {}) => {
    if (fill) doc.rect(startX, top, totalWidth, height).fill(fill);
    doc.font(bold ? 'Helvetica-Bold' : 'Helvetica').fontSize(fontSize).fillColor(textColor);
    let cx = startX;
    for (let i = 0; i < columns.length; i++) {
      doc.text(String(cells[i] ?? ''), cx + padH, top + padV, {
        width: columns[i].width - padH * 2,
        align: columns[i].align || 'left',
        lineBreak: true,
      });
      cx += columns[i].width;
    }
    // Outer border + vertical separators.
    doc.lineWidth(0.5).strokeColor(BORDER).rect(startX, top, totalWidth, height).stroke();
    let vx = startX;
    for (let i = 0; i < columns.length - 1; i++) {
      vx += columns[i].width;
      doc.moveTo(vx, top).lineTo(vx, top + height).stroke();
    }
  };

  const headerCells = columns.map((c) => c.label);
  const drawHeader = () => {
    const h = measure(headerCells, true);
    paint(headerCells, doc.y, h, { bold: true, fill: NAVY, textColor: '#ffffff' });
    doc.y += h;
  };

  drawHeader();
  rows.forEach((cells, idx) => {
    const rowH = measure(cells, false);
    if (doc.y + rowH > doc.page.height - doc.page.margins.bottom) {
      doc.addPage();
      drawHeader();
    }
    const zebra = idx % 2 === 1 ? ZEBRA : null;
    const textColor = rowColors[idx] || INK;
    paint(cells, doc.y, rowH, { fill: zebra, textColor });
    doc.y += rowH;
  });

  doc.x = doc.page.margins.left;
  doc.y += 10;
}

// ─── Section renderers ───────────────────────────────────────────────

/**
 * Cover page — full-bleed banner, headline figures, and a sign-off block.
 *
 * @param {PDFKit.PDFDocument} doc
 * @param {{ ackNo: string, generatedStr: string, victimLoss: number,
 *   trailDisputed: number, totalTxns: number, totalLayers: number,
 *   fraudStart: string }} c
 */
function renderCover(doc, c) {
  const left = doc.page.margins.left;

  // Banner.
  doc.save();
  doc.rect(0, 0, doc.page.width, 150).fill(NAVY);
  doc.fillColor('#ffffff').font('Helvetica-Bold').fontSize(28).text('FinTrace NCRP', left, 48);
  doc.font('Helvetica').fontSize(13)
    .text('Cyber Crime Financial Trail — Investigation Dossier', left, 92);
  doc.restore();

  doc.fillColor(INK).font('Helvetica-Bold').fontSize(20)
    .text('Investigation Report', left, 195);
  doc.moveDown(1.2);
  doc.x = left;

  drawTable(doc, {
    fontSize: 11,
    columns: [
      { label: 'Field', width: 200 },
      { label: 'Value', width: contentWidth(doc) - 200 },
    ],
    rows: [
      ['Case / Acknowledgement No.', c.ackNo],
      ['Report Generated', c.generatedStr],
      ['Fraud Trail Start Date', c.fraudStart],
      ['Victim Loss (Layer 1)', formatMoney(c.victimLoss)],
      ['Total Trail Disputed (all layers)', formatMoney(c.trailDisputed)],
      ['Total Transactions', formatCount(c.totalTxns)],
      ['Layers Detected', formatCount(c.totalLayers)],
    ],
  });

  doc.moveDown(2);
  doc.x = left;
  doc.font('Helvetica-Bold').fontSize(11).fillColor(INK);
  const line = (label) => {
    doc.text(`${label}  `, left, doc.y, { continued: true })
      .font('Helvetica').fillColor(MUTED).text('______________________________________')
      .font('Helvetica-Bold').fillColor(INK);
    doc.moveDown(0.8);
  };
  doc.text('Prepared / reviewed by:', left, doc.y);
  doc.moveDown(0.8);
  line('Case Officer :');
  line('Designation  :');
  line('Signature    :');
  line('Date         :');

  doc.moveDown(1.5);
  doc.font('Helvetica-Oblique').fontSize(8.5).fillColor(MUTED).text(
    'CONFIDENTIAL — For official use only. This dossier is generated from an NCRP ' +
    'BankAction CompleteTrail export and is intended solely for authorised ' +
    'investigation and judicial proceedings.',
    left, doc.y, { width: contentWidth(doc) }
  );
}

/**
 * @param {PDFKit.PDFDocument} doc
 * @param {object} a - The analysis bundle.
 * @param {Array<object>} liens
 */
function renderExecutiveSummary(doc, a, liens) {
  sectionHeading(doc, '2. Executive Summary');
  para(doc,
    'Key figures for this case at a glance. Detailed breakdowns follow in the ' +
    'subsequent sections.', { gap: 0.8 });

  const summary = a.summary || {};
  const cashout = a.cashout_analysis || {};
  const mules = a.mule_detection || [];
  const highMules = mules.filter((m) => m.risk_label === 'HIGH').length;
  // Two distinct figures — never conflate (see analyzer summary):
  //   • recoverableResidual: victim loss not yet cashed out / frozen / refunded.
  //   • lienTableTotal: Σ per-account lien-eligible balances (can exceed the loss).
  const recoverableResidual = num(summary.recoverable_residual);
  const lienTableTotal = num(summary.lien_table_total) || (liens || []).reduce(
    (s, l) => s + num(l.lien_amount ?? l.lien_eligible_amount), 0);
  const banks = new Set((liens || []).map((l) => l.bank_name).filter(Boolean)).size;
  const cashedOut = cashedOutForDisplay(summary, cashout);

  drawTable(doc, {
    fontSize: 10,
    columns: [
      { label: 'Metric', width: 300 },
      { label: 'Value', width: contentWidth(doc) - 300, align: 'right' },
    ],
    rows: [
      ['Total transactions analysed', formatCount(summary.total_transactions)],
      ['Victim loss (Layer 1)', formatMoney(summary.victim_loss_amount ?? summary.total_disputed_amount)],
      ['Total trail disputed (all layers)', formatMoney(summary.total_trail_disputed ?? summary.total_disputed_amount)],
      ['Layers in the money trail', formatCount(summary.total_layers)],
      ['Distinct beneficiary accounts', formatCount(summary.total_accounts)],
      ['Fraud trail start date', formatDate(summary.fraud_start_date)],
      ['Total confirmed cashed out (ATM/POS)', formatMoney(cashedOut)],
      ['Recoverable residual (loss - cashed out - on hold - refunded)', formatMoney(recoverableResidual)],
      ['Same-day ATM cashouts', formatCount(cashout.same_day_cashouts)],
      ['High-risk mule accounts', formatCount(highMules)],
      ['Accounts with lien-eligible balance', formatCount((liens || []).length)],
      ['Total lien-eligible balance across flagged accounts', formatMoney(lienTableTotal)],
      ['Banks to be contacted for lien', formatCount(banks)],
    ],
  });

  para(doc,
    'Recoverable residual is the share of the victim loss not yet cashed out, frozen, or refunded — ' +
    'it sums with those to 100% of the loss. The total lien-eligible balance is the per-account freezable ' +
    'sum and may exceed the victim loss because funds are re-counted as they traverse multiple layers.',
    { gap: 0.6, size: 8.5, color: MUTED });

  para(doc, 'Note: visual charts are available on the FinTrace dashboard. This ' +
    'PDF presents the complete underlying data as tables.',
    { gap: 0, size: 8.5, color: MUTED });
}

/** @param {PDFKit.PDFDocument} doc @param {Array<object>} roadmap */
function renderRoadmap(doc, roadmap) {
  sectionHeading(doc, '3. Investigation Roadmap');
  para(doc,
    'Prioritised actions for the investigating officer, ordered P0 (act now) ' +
    'through P3 (corroborating evidence). Row colour signals urgency: ' +
    'P0 red, P1 amber, P2 blue, P3 grey.', { gap: 0.8 });

  const list = Array.isArray(roadmap) ? roadmap : [];
  if (list.length === 0) {
    para(doc, 'No roadmap actions were generated for this case.', { color: MUTED });
    return;
  }

  drawTable(doc, {
    fontSize: 9,
    rowColors: list.map((r) => PRIORITY_COLOR[r.priority] || INK),
    columns: [
      { label: 'Priority', width: 75, align: 'center' },
      { label: 'Action', width: 165 },
      { label: 'Description', width: contentWidth(doc) - 240 },
    ],
    rows: list.map((r) => [
      PRIORITY_LABEL[r.priority] || r.priority || '—',
      asciiSafe(r.title),
      asciiSafe(r.description),
    ]),
  });
}

/** @param {PDFKit.PDFDocument} doc @param {Array<object>} layers */
function renderLayers(doc, layers) {
  sectionHeading(doc, '4. Layer-by-Layer Analysis');
  para(doc,
    'Each layer is one hop further from the victim. Funds typically fan out and ' +
    'speed up as they move outward toward cashout points.', { gap: 0.8 });

  if (!layers || layers.length === 0) {
    para(doc, 'No layer data available.', { color: MUTED });
    return;
  }

  drawTable(doc, {
    columns: [
      { label: 'Layer', width: 55, align: 'center' },
      { label: 'Accounts', width: 70, align: 'right' },
      { label: 'Total Amount', width: 110, align: 'right' },
      { label: 'Disputed', width: 105, align: 'right' },
      { label: 'Cashouts', width: 70, align: 'right' },
      { label: 'Avg Fwd (hrs)', width: contentWidth(doc) - 410, align: 'right' },
    ],
    rows: layers.map((l) => [
      `L${l.layer_no}`,
      formatCount(l.account_count),
      formatMoney(l.total_amount),
      formatMoney(l.disputed_amount),
      formatCount(l.cashout_count),
      l.avg_forward_time_hours == null ? '—' : num(l.avg_forward_time_hours).toFixed(2),
    ]),
  });
}

/** @param {PDFKit.PDFDocument} doc @param {object} network - money_flow_network. */
function renderMoneyFlow(doc, network) {
  sectionHeading(doc, '5. Money Flow Network');
  para(doc,
    'The heaviest account-to-account transfers in the trail (top 10 by amount), ' +
    'aggregated across every hop between each pair. Account numbers are masked.',
    { gap: 0.8 });

  const edges = (network && Array.isArray(network.top_edges))
    ? network.top_edges.slice(0, 10) : [];
  if (edges.length === 0) {
    para(doc, 'No account-to-account edges were derived for this case.', { color: MUTED });
    return;
  }

  drawTable(doc, {
    fontSize: 8.5,
    columns: [
      { label: 'Source A/c (masked)', width: 100 },
      { label: 'Destination (masked)', width: 100 },
      { label: 'Amount', width: 95, align: 'right' },
      { label: 'Txns', width: 40, align: 'right' },
      { label: 'Layers', width: 45, align: 'center' },
      { label: 'Bank', width: contentWidth(doc) - 380 },
    ],
    rows: edges.map((e) => [
      maskAccount(e.source),
      maskAccount(e.destination),
      formatMoney(e.amount),
      formatCount(e.txn_count),
      e.layers == null || e.layers === '' ? '—' : String(e.layers),
      asciiSafe(e.banks) || '—',
    ]),
  });
}

/** @param {PDFKit.PDFDocument} doc @param {Array<object>} mules */
function renderMules(doc, mules) {
  sectionHeading(doc, '6. Top Mule Accounts');
  para(doc,
    'Accounts ranked by mule risk score (higher = stronger mule indicators). ' +
    'HIGH-risk accounts are the priority targets for lien and KYC requests. ' +
    'Account numbers are masked for the report.',
    { gap: 0.8 });

  const top = (mules || []).slice(0, 10);
  if (top.length === 0) {
    para(doc, 'No mule accounts were scored.', { color: MUTED });
    return;
  }

  drawTable(doc, {
    fontSize: 8.5,
    rowColors: top.map((m) => RISK_COLOR[m.risk_label] || INK),
    columns: [
      { label: '#', width: 24, align: 'center' },
      { label: 'Account (masked)', width: 95 },
      { label: 'Bank', width: 95 },
      { label: 'Layer', width: 42, align: 'center' },
      { label: 'Score', width: 42, align: 'right' },
      { label: 'Risk', width: 55, align: 'center' },
      { label: 'Received', width: contentWidth(doc) - 353, align: 'right' },
    ],
    rows: top.map((m, i) => [
      i + 1,
      maskAccount(m.account_no),
      m.bank_name || '—',
      m.layer_no == null ? '—' : `L${m.layer_no}`,
      formatCount(m.mule_score),
      m.risk_label || '—',
      formatMoney(m.total_received),
    ]),
  });
}

/** @param {PDFKit.PDFDocument} doc @param {Array<object>} liens */
function renderLien(doc, liens) {
  sectionHeading(doc, '7. Lien-Eligible Amounts');
  para(doc,
    'Lien-eligible balance per account — disputed inflow not yet confirmed withdrawn ' +
    'as cash. Subject to the actual available balance confirmed by the bank.',
    { gap: 0.8 });

  if (!liens || liens.length === 0) {
    para(doc, 'No accounts currently carry a lien-eligible balance.', { color: MUTED });
    return;
  }

  const total = liens.reduce((s, l) => s + num(l.lien_amount ?? l.lien_eligible_amount), 0);
  drawTable(doc, {
    fontSize: 8.5,
    columns: [
      { label: '#', width: 24, align: 'center' },
      { label: 'Account (masked)', width: 100 },
      { label: 'Bank', width: 110 },
      { label: 'IFSC', width: 85 },
      { label: 'Status', width: 60, align: 'center' },
      { label: 'Lien Amount', width: contentWidth(doc) - 379, align: 'right' },
    ],
    rows: liens.map((l, i) => [
      i + 1,
      maskAccount(l.account_no),
      l.bank_name || '—',
      l.ifsc_code || '—',
      l.lien_status || 'pending',
      formatMoney(l.lien_amount ?? l.lien_eligible_amount),
    ]),
  });

  para(doc, `Total lien-eligible balance across ${formatCount(liens.length)} flagged account(s): ` +
    `${formatMoney(total)}.`, { bold: true, gap: 0.4 });
  para(doc,
    '(May exceed the victim loss as funds traverse multiple layers — this is the freezable ' +
    'per-account balance, not the recoverable residual reported in the Executive Summary.)',
    { gap: 0, size: 8, color: MUTED });
}

/** @param {PDFKit.PDFDocument} doc @param {object} cashout */
function renderCashout(doc, cashout) {
  sectionHeading(doc, '8. Cashout Analysis');
  const c = cashout || {};

  para(doc, `Total confirmed cashed out (ATM + POS): ${formatMoney(c.total_cashout_amount)} ` +
    `across ${formatCount(c.total_cashout_transactions)} transaction(s).`, { gap: 0.3 });
  para(doc, `Same-day ATM cashouts: ${formatCount(c.same_day_cashouts)}` +
    (c.fastest_cashout_hours != null
      ? `   |   Fastest cashout: ${num(c.fastest_cashout_hours).toFixed(2)} hours after victim debit.`
      : '.'), { gap: 0.9 });

  const atms = c.atm_cashouts || [];
  if (atms.length > 0) {
    para(doc, 'ATM withdrawal locations (highest value first):', { bold: true, gap: 0.5 });
    drawTable(doc, {
      fontSize: 8.5,
      columns: [
        { label: 'ATM ID', width: 80 },
        { label: 'Location', width: 150 },
        { label: 'City', width: 80 },
        { label: 'State', width: 80 },
        { label: 'Amount', width: contentWidth(doc) - 460, align: 'right' },
        { label: 'Hits', width: 30, align: 'right' },
      ],
      rows: atms.map((a) => [
        a.atm_id || '—',
        a.atm_location || '—',
        a.city || '—',
        a.state || '—',
        formatMoney(a.amount),
        formatCount(a.count),
      ]),
    });
  } else {
    para(doc, 'No ATM/POS cashouts were detected in this trail.', { color: MUTED, gap: 0.9 });
  }

  const byState = c.cashout_by_state || [];
  if (byState.length > 0) {
    para(doc, 'Cashout distribution by state:', { bold: true, gap: 0.5 });
    drawTable(doc, {
      fontSize: 9,
      columns: [
        { label: 'State', width: 220 },
        { label: 'Cashout Amount', width: 150, align: 'right' },
        { label: 'Count', width: contentWidth(doc) - 370, align: 'right' },
      ],
      rows: byState.map((s) => [s.state, formatMoney(s.amount), formatCount(s.count)]),
    });
  }
}

