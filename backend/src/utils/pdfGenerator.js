/**
 * Generate the investigation PDF for one report and write it to `outputPath`.
 *
 * The promise resolves with `outputPath` once the file stream has fully
 * flushed, or rejects if PDFKit or the write stream errors. The parent
 * directory is created if missing.
 *
 * @param {{
 *   report?: Record<string, unknown>,
 *   analysis?: Record<string, unknown>,
 *   liens?: Array<Record<string, unknown>>,
 *   emails?: Array<Record<string, unknown>>,
 *   layers?: Array<Record<string, unknown>>,
 *   transactions?: Array<Record<string, unknown>>,
 *   ack_no?: string|null,
 *   complaint_date?: string|null,
 * }} data - The report's analysis bundle (analysis = parsed analysis_json).
 *   `transactions` (the raw ledger) drives the writer-side ATM/POS split and
 *   the POS merchant table; without it those sections fall back to the
 *   analyzer's views.
 * @param {string} outputPath - Absolute path of the .pdf to write.
 * @returns {Promise<string>} Resolves to `outputPath`.
 *
 * @example
 *   await generateReportPdf({ report, analysis, liens, emails, layers },
 *     path.join(exportsDir, 'FinTrace-NCRP123-1716800000000.pdf'));
 */
function generateReportPdf(data, outputPath) {
  return new Promise((resolve, reject) => {
    try {
      fs.mkdirSync(path.dirname(outputPath), { recursive: true });
    } catch (err) {
      reject(new Error(`generateReportPdf: cannot create output directory: ${err.message}`));
      return;
    }

    const {
      report = {}, analysis = {}, liens = [], emails = [], layers = [], transactions = [],
    } = data || {};
    const summary = analysis.summary || {};
    // Prefer persisted layer rows; fall back to the analysis snapshot.
    const layerRows = (layers && layers.length) ? layers : (analysis.layer_analysis || []);
    const ackNo = (data && data.ack_no) || report.ack_no || `report-${report.id ?? '—'}`;

    // Writer-side ATM/POS scoping + gross-vs-confirmed reconciliation (shared
    // with the XLSX export via exportViews — presentation only, no money math).
    // With no ledger available the ATM table falls back to the analyzer's full
    // terminal list, exactly as before.
    const cashoutView = analysis.cashout_analysis || {};
    const atmTerminals = transactions.length
      ? atmOnlyCashouts(cashoutView.atm_cashouts || [], transactions)
      : (cashoutView.atm_cashouts || []);
    const geoView = analysis.geography || {};
    // Ledger-derived merchants are complete (the analyzer's top_merchants view
    // is name-grouped, top-10, and empty whenever POS legs carry terminal ids).
    const posMerchants = transactions.length
      ? posMerchantAggregates(transactions)
      : (Array.isArray(geoView.top_merchants) ? geoView.top_merchants : []);
    const atmShownAmount = atmTerminals.reduce((s, a) => s + num(a.amount), 0);
    const atmShownTxns = atmTerminals.reduce((s, a) => s + num(a.count), 0);
    const posShownAmount = posMerchants.reduce((s, m) => s + num(m.amount), 0);
    const posShownTxns = posMerchants.reduce((s, m) => s + num(m.txn_count), 0);
    const cashoutRecon = cashoutReconciliation(
      { summary, cashout: cashoutView },
      atmShownAmount + posShownAmount, atmShownTxns + posShownTxns);

    // Visual-summary charts: SVG built + rasterised to deterministic PNGs (same
    // case -> same charts). Wrapped so a rasteriser failure can never abort the
    // dossier — renderCharts degrades to nulls and the Visual Summary prints a
    // pointer to the Annexure tables instead.
    let charts;
    try {
      charts = renderCharts(analysis, transactions);
    } catch (err) {
      charts = { available: false, network: null, layers: null, timeline: null };
    }

    // Evidentiary provenance, read from the persisted report record (with
    // explicit-override fallbacks so callers/tests can pass it directly).
    const provenance = {
      sha256: report.source_sha256 ?? (data && data.source_sha256) ?? null,
      filename: report.original_filename ?? (data && data.source_filename) ?? null,
      ingestedAt: report.upload_date ?? (data && data.upload_date) ?? null,
      // A persisted app_version of "unknown" (older uploads, before the version
      // was wired in) must not mask the real version — treat it as absent so
      // appVersion() fills in.
      version: (data && typeof data.app_version === 'string' && data.app_version.trim()
        && data.app_version.trim().toLowerCase() !== 'unknown')
        ? data.app_version.trim() : appVersion(),
    };

    const doc = new PDFDocument({
      size: 'A4',
      margin: PAGE_MARGIN,
      bufferPages: true,
      info: {
        Title: `FinTrace NCRP Investigation Report — ${ackNo}`,
        Author: 'FinTrace NCRP | MINT',
        Subject: 'Cyber Crime Financial Trail Analysis',
        // Embed the source hash in the PDF metadata (item 3) so the provenance
        // survives even if the document text is stripped.
        Keywords: provenance.sha256
          ? `source-sha256:${provenance.sha256}; source-file:${provenance.filename || ''}; `
            + `fintrace-version:${provenance.version}`
          : `fintrace-version:${provenance.version}`,
        Creator: `FinTrace NCRP v${provenance.version}`,
      },
    });

    const stream = fs.createWriteStream(outputPath);
    let settled = false;
    const fail = (err) => {
      if (settled) return;
      settled = true;
      reject(err instanceof Error ? err : new Error(String(err)));
    };
    stream.on('error', fail);
    doc.on('error', fail);
    stream.on('finish', () => {
      if (settled) return;
      settled = true;
      resolve(outputPath);
    });

    doc.pipe(stream);

    // Global glyph sanitizer: PDFKit's built-in WinAnsi Helvetica has no glyph
    // for U+2212, en/em dashes, smart quotes, ellipsis, ₹, ≥, etc. — they render
    // as blank boxes (a "−" shows as a stray double-quote). Route EVERY drawn
    // string and its layout measurement through asciiSafe so both agree, catching
    // table cells, headings, paragraphs, cover, footers, and the '—' fallbacks
    // that bypass the per-field asciiSafe() calls.
    const drawText = doc.text.bind(doc);
    doc.text = (str, ...rest) => drawText(asciiSafe(str), ...rest);
    const measureHeight = doc.heightOfString.bind(doc);
    doc.heightOfString = (str, ...rest) => measureHeight(asciiSafe(str), ...rest);

    try {
      // 1. Cover (current first page). Headline money figure is the Layer-1
      // victim loss (the actual amount stolen); the all-layers trail-disputed
      // figure re-counts the same money across hops and is shown beneath it.
      renderCover(doc, {
        ackNo: String(ackNo),
        generatedStr: formatDate(new Date().toISOString()),
        victimLoss: summary.victim_loss_amount
          ?? summary.total_disputed_amount ?? report.total_disputed_amount,
        trailDisputed: summary.total_trail_disputed
          ?? summary.total_disputed_amount ?? report.total_disputed_amount,
        totalTxns: summary.total_transactions ?? report.total_transactions,
        totalLayers: summary.total_layers ?? report.total_layers,
        fraudStart: formatDate(summary.fraud_start_date ?? report.fraud_start_date),
        provenance,
      });

      // ── Front matter ──────────────────────────────────────────────────
      doc.addPage(); renderExecutiveSummary(doc, analysis, liens);
      doc.addPage(); renderVisualSummary(doc, charts);
      doc.addPage(); renderRoadmap(doc, analysis.investigation_roadmap || []);
      doc.addPage(); renderFindings(doc, analysis.key_findings || []);

      // ── Annexure (bulky tables, behind a divider page) ─────────────────
      doc.addPage(); renderAnnexureDivider(doc);
      doc.addPage(); renderLayers(doc, layerRows, analysis.reconciliation);
      doc.addPage(); renderMoneyFlow(doc, analysis.money_flow_network || {}, analysis.aggregators || []);
      doc.addPage(); renderCircularFlows(doc, analysis.circular_flows || []);
      doc.addPage(); renderMules(doc, analysis.mule_detection || []);
      doc.addPage(); renderLien(doc, liens);
      doc.addPage(); renderCashout(doc, cashoutView, { atmTerminals, recon: cashoutRecon });
      doc.addPage(); renderGeography(doc, geoView, posMerchants);
      doc.addPage(); renderTimeline(doc, analysis.timeline || [], analysis.reconciliation, analysis.day_of_week);
      // Annexure H — bank-attribution data-quality review (adds its own page).
      // Includes the parser self-healing audit (fuzzy matches / degraded columns).
      renderDataQuality(doc, analysis.data_quality || [], analysis.old_transactions || [],
        analysis.parse_warnings || []);

      // Draft emails (adds its own pages). Pass the full analysis so renderEmails
      // can derive the wallet/masked non-actionable sections and the per-letter
      // "verify bank" reviewer note (freeze-target set).
      renderEmails(doc, emails, analysis);

      // Footer + page numbers + per-page source hash across every buffered page.
      stampFooters(doc, provenance);
    } catch (err) {
      fail(err);
      return;
    }

    doc.end();
  });
}

