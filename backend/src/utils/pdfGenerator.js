/**
 * Generate the investigation PDF for one report and write it to `outputPath`.
 *
 * The promise resolves with `outputPath` once the file stream has fully
 * flushed, or rejects if PDFKit or the write stream errors. The parent
 * directory is created if missing.
 *
 * @param {{
 *   report?: Record<string, unknown>,
 *   analysis?: Record<string, unknown>,
 *   liens?: Array<Record<string, unknown>>,
 *   emails?: Array<Record<string, unknown>>,
 *   layers?: Array<Record<string, unknown>>,
 *   ack_no?: string|null,
 *   complaint_date?: string|null,
 * }} data - The report's analysis bundle (analysis = parsed analysis_json).
 * @param {string} outputPath - Absolute path of the .pdf to write.
 * @returns {Promise<string>} Resolves to `outputPath`.
 *
 * @example
 *   await generateReportPdf({ report, analysis, liens, emails, layers },
 *     path.join(exportsDir, 'FinTrace-NCRP123-1716800000000.pdf'));
 */
function generateReportPdf(data, outputPath) {
  return new Promise((resolve, reject) => {
    try {
      fs.mkdirSync(path.dirname(outputPath), { recursive: true });
    } catch (err) {
      reject(new Error(`generateReportPdf: cannot create output directory: ${err.message}`));
      return;
    }

    const {
      report = {}, analysis = {}, liens = [], emails = [], layers = [],
    } = data || {};
    const summary = analysis.summary || {};
    // Prefer persisted layer rows; fall back to the analysis snapshot.
    const layerRows = (layers && layers.length) ? layers : (analysis.layer_analysis || []);
    const ackNo = (data && data.ack_no) || report.ack_no || `report-${report.id ?? '—'}`;

    const doc = new PDFDocument({
      size: 'A4',
      margin: PAGE_MARGIN,
      bufferPages: true,
      info: {
        Title: `FinTrace NCRP Investigation Report — ${ackNo}`,
        Author: 'FinTrace NCRP | MINT',
        Subject: 'Cyber Crime Financial Trail Analysis',
      },
    });

    const stream = fs.createWriteStream(outputPath);
    let settled = false;
    const fail = (err) => {
      if (settled) return;
      settled = true;
      reject(err instanceof Error ? err : new Error(String(err)));
    };
    stream.on('error', fail);
    doc.on('error', fail);
    stream.on('finish', () => {
      if (settled) return;
      settled = true;
      resolve(outputPath);
    });

    doc.pipe(stream);

    // Global glyph sanitizer: PDFKit's built-in WinAnsi Helvetica has no glyph
    // for U+2212, en/em dashes, smart quotes, ellipsis, ₹, ≥, etc. — they render
    // as blank boxes (a "−" shows as a stray double-quote). Route EVERY drawn
    // string and its layout measurement through asciiSafe so both agree, catching
    // table cells, headings, paragraphs, cover, footers, and the '—' fallbacks
    // that bypass the per-field asciiSafe() calls.
    const drawText = doc.text.bind(doc);
    doc.text = (str, ...rest) => drawText(asciiSafe(str), ...rest);
    const measureHeight = doc.heightOfString.bind(doc);
    doc.heightOfString = (str, ...rest) => measureHeight(asciiSafe(str), ...rest);

    try {
      // 1. Cover (current first page). Headline money figure is the Layer-1
      // victim loss (the actual amount stolen); the all-layers trail-disputed
      // figure re-counts the same money across hops and is shown beneath it.
      renderCover(doc, {
        ackNo: String(ackNo),
        generatedStr: formatDate(new Date().toISOString()),
        victimLoss: summary.victim_loss_amount
          ?? summary.total_disputed_amount ?? report.total_disputed_amount,
        trailDisputed: summary.total_trail_disputed
          ?? summary.total_disputed_amount ?? report.total_disputed_amount,
        totalTxns: summary.total_transactions ?? report.total_transactions,
        totalLayers: summary.total_layers ?? report.total_layers,
        fraudStart: formatDate(summary.fraud_start_date ?? report.fraud_start_date),
      });

      // 2-11. One section per page.
      doc.addPage(); renderExecutiveSummary(doc, analysis, liens);
      doc.addPage(); renderRoadmap(doc, analysis.investigation_roadmap || []);
      doc.addPage(); renderLayers(doc, layerRows);
      doc.addPage(); renderMoneyFlow(doc, analysis.money_flow_network || {});
      doc.addPage(); renderMules(doc, analysis.mule_detection || []);
      doc.addPage(); renderLien(doc, liens);
      doc.addPage(); renderCashout(doc, analysis.cashout_analysis || {});
      doc.addPage(); renderGeography(doc, analysis.geography || {});
      doc.addPage(); renderTimeline(doc, analysis.timeline || []);
      doc.addPage(); renderFindings(doc, analysis.key_findings || []);

      // 12. Bank-attribution data-quality review (adds its own page).
      renderDataQuality(doc, analysis.data_quality || []);

      // 13. Draft emails (adds its own pages). Pass the flagged accounts so each
      // letter can carry a reviewer note where its bank was IFSC-corrected.
      renderEmails(doc, emails, analysis.data_quality || []);

      // Footer + page numbers across every buffered page.
      stampFooters(doc);
    } catch (err) {
      fail(err);
      return;
    }

    doc.end();
  });
}

